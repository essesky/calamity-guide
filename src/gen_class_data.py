def check(d, name):
    for t in (d["main"]["tiers"] + (d["alt"]["tiers"] if d.get("alt") else [])):
        if not t["mats"]:
            problems.append("%s: %s 无配方原料" % (name, t["w"]))
    for r in d["side"]["rows"]:
        if r["from"] not in IT:
            problems.append("%s side from 缺失: %s" % (name, r["from"]))
        if r["to"] not in IT:
            problems.append("%s side to 缺失: %s" % (name, r["to"]))
    for r in d["fusion"]["rows"]:
        if r["out"] not in IT:
            problems.append("%s fusion 缺失: %s" % (name, r["out"]))
    for g in d["kit"]["groups"]:
        for k in g["items"]:
            if k not in IT:
                problems.append("%s kit 缺失: %s" % (name, k))


