import json
from pathlib import Path

base = Path(__file__).resolve().parent
D = json.load(open(base / "app_data_final.json", encoding="utf-8"))
IT, NM = D["items"], D["names"]
VR = json.load(open(base / "vanilla_recipes.json", encoding="utf-8"))

ST_MAP = {"Mythril Anvil": "秘银砧", "Iron Anvil": "铁砧", "Ancient Manipulator": "远古操纵机",
          "Bookcase": "书架", "Work Bench": "工作台", "Furnace": "熔炉"}


def recipe_of(key):
    """返回 (站名, [[原料键, 数量], ...]) 或 (None, [])"""
    v = IT.get(key) or {}
    rs = v.get("r") or []
    if rs:
        st, ing = rs[0][0], rs[0][1]
        return st, [[a, q] for a, q in ing]
    for r in (VR.get(key) or []):
        return ST_MAP.get(r["s"], r["s"]), [[a, q] for a, q in r["i"]]
    return None, []


def tier(no, key, when, why, how, dmg="—"):
    st, mats = recipe_of(key)
    return {"no": str(no), "when": when, "w": key, "dmg": dmg,
            "st": st or "—", "mats": mats, "why": why, "how": how}


def side(frm, to, note, st=None):
    st2, mats = recipe_of(to)
    need = [m for m in mats if m[0] != frm]
    return {"from": frm, "to": to, "st": st or st2 or "—", "dmg": "",
            "need": need, "note": note}


def fusion(out, note, st=None):
    st2, mats = recipe_of(out)
    return {"out": out, "st": st or st2 or "—", "dmg": "", "need": mats, "note": note}


